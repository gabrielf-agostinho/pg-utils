SELECT pg_temp.assert_equals(util.table_exists('util', 'holidays'), true, 'table_exists');
SELECT pg_temp.assert_equals(util.table_exists('util', 'nao_existe'), false, 'table_exists inexistente');

SELECT pg_temp.assert_equals(util.column_exists('util', 'holidays', 'date'), true, 'column_exists');
SELECT pg_temp.assert_equals(util.column_exists('util', 'holidays', 'foo'), false, 'column_exists inexistente');

SELECT pg_temp.assert_equals(
    (SELECT count(*) > 0 FROM util.table_sizes('util') WHERE table_name = 'holidays'),
    true,
    'table_sizes'
);

CREATE TABLE pg_temp.t_seq (id INTEGER GENERATED BY DEFAULT AS IDENTITY, nome TEXT);
CREATE TABLE pg_temp.t_serial (id SERIAL, nome TEXT);

SELECT pg_temp.assert_equals(util.reset_sequence('pg_temp.t_seq'), 1::BIGINT, 'reset_sequence tabela vazia');

INSERT INTO pg_temp.t_seq (id, nome) VALUES (10, 'a'), (42, 'b');
INSERT INTO pg_temp.t_serial (id, nome) VALUES (7, 'a');

SELECT pg_temp.assert_equals(util.reset_sequence('pg_temp.t_seq', 'id'), 43::BIGINT, 'reset_sequence identity');

INSERT INTO pg_temp.t_seq (nome) VALUES ('c');
SELECT pg_temp.assert_equals((SELECT max(id) FROM pg_temp.t_seq), 43, 'reset_sequence próximo id');

SELECT pg_temp.assert_equals(
    (SELECT next_value FROM util.reset_all_sequences(pg_my_temp_schema()::regnamespace::TEXT)
      WHERE table_name LIKE '%t_serial'),
    8::BIGINT,
    'reset_all_sequences'
);
